// Convert data/reading/passages-with-questions.json (real Wikipedia passages
// + Gemini-generated, source-anchored IELTS questions) into the TypeScript
// module the app imports.
//
// Run after build-reading.mjs and build-reading-questions.mjs.

import { readFile, writeFile } from "node:fs/promises";

const SRC = new URL("../data/reading/passages-with-questions.json", import.meta.url);
const OUT = new URL("../data/reading/passages.ts", import.meta.url);

const passages = JSON.parse(await readFile(SRC, "utf-8"));

// Normalise the Gemini-emitted question types to the app's union.
const TYPE_MAP = {
  multiple_choice: "mcq",
  tfng: "tfng",
  ynng: "ynng",
  matching_information: "matching_information",
  matching_headings: "matching_headings",
  matching_features: "matching_features",
  matching_sentence_endings: "matching_sentence_endings",
  short_answer: "short_answer",
  summary_completion: "summary_completion",
  sentence_completion: "sentence_completion",
  note_completion: "note_completion",
  table_completion: "table_completion",
  flowchart_completion: "flowchart_completion",
};

function tsString(s) {
  // Escape backticks and ${} for template literals.
  return "`" + String(s).replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";
}

function tsArray(arr) {
  return "[" + arr.map(tsString).join(", ") + "]";
}

let out = `// AUTO-GENERATED by scripts/emit-reading-ts.mjs — do not edit by hand.
// Source: real passages from Wikipedia (CC-BY-SA 4.0), trimmed to the IELTS
// 700–900-word target. IELTS-style questions are answer-grounded against the
// passage text. Each passage carries its original-source URL and licence.

import { ReadingQuestionType } from "@/lib/ielts/question-types";

export interface ReadingQuestion {
  num: number;
  type: ReadingQuestionType;
  question: string;
  options?: string[];
  /**
   * For multi-answer questions, expected is a string array. For single-answer
   * questions it's a string. Multiple acceptable answers can be encoded in
   * a single answer string separated by " | ".
   */
  expected: string | string[];
  explanation: string;
  paragraphRef?: string;
  bandLevel: number;
}

export interface ReadingPassage {
  id: string;
  title: string;
  source: string;
  /** URL of the original source. Always set for real-source passages. */
  sourceUrl?: string;
  /** SPDX-style licence label, e.g. "CC-BY-SA-4.0". */
  licence?: string;
  /** Plain-text attribution string ready to render in the UI. */
  attribution?: string;
  difficulty: "band6" | "band7" | "band8" | "band9";
  topic: "science" | "society" | "humanities" | "history" | "psychology" | "environment";
  paragraphs: string[];
  questions: ReadingQuestion[];
  wordCount?: number;
}

export const READING_PASSAGES: ReadingPassage[] = [
`;

for (const p of passages) {
  out += "  {\n";
  out += `    id: ${tsString(p.id)},\n`;
  out += `    title: ${tsString(p.title)},\n`;
  out += `    source: ${tsString("Wikipedia")},\n`;
  out += `    sourceUrl: ${tsString(p.sourceUrl)},\n`;
  out += `    licence: ${tsString("CC-BY-SA-4.0")},\n`;
  out += `    attribution: ${tsString(p.attribution)},\n`;
  out += `    difficulty: "${p.difficulty}",\n`;
  out += `    topic: "${p.topic}",\n`;
  out += `    wordCount: ${p.wordCount},\n`;
  out += `    paragraphs: ${tsArray(p.paragraphs)},\n`;
  out += "    questions: [\n";
  for (const q of p.questions) {
    const type = TYPE_MAP[q.type] || q.type;
    out += "      {\n";
    out += `        num: ${q.num},\n`;
    out += `        type: "${type}",\n`;
    out += `        question: ${tsString(q.question)},\n`;
    if (q.options) out += `        options: ${tsArray(q.options)},\n`;
    out += `        expected: ${tsString(String(q.expected))},\n`;
    out += `        explanation: ${tsString(q.explanation)},\n`;
    if (q.paragraphRef) out += `        paragraphRef: ${tsString(q.paragraphRef)},\n`;
    out += `        bandLevel: ${q.bandLevel},\n`;
    out += "      },\n";
  }
  out += "    ],\n";
  out += "  },\n";
}
out += "];\n";

await writeFile(OUT, out, "utf-8");
console.log(`Wrote ${passages.length} passages → ${OUT.pathname}`);
